import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import {
  PROFILE_MD_CAP,
  buildEvaluatorMessages,
  buildTailorMessages,
  buildTaskMessages,
  buildWriterMessages,
  profileMdBlock,
  profileMdHasContent,
} from '../lib/prompts.js';

// modes/_profile.md is the candidate's own targeting — what they are going for
// and how to argue it. Evaluation scores against it. These tests pin that it
// reaches the model, that an empty one does not waste context, and that adding
// it cannot push a user turn past numCtx.

const SECTION_HEADINGS = [
  '## Your Target Roles', '## Your Adaptive Framing', '## Your Exit Narrative',
  '## Your Cross-cutting Advantage', '## Your Portfolio / Demo', '## Your Comp Targets',
  '## Your Negotiation Scripts', '## Your Location Policy',
];

const EMPTY_MD = [
  '# User Profile Context -- career-ops',
  '',
  '<!-- Generated by JobHacker Compass. Sections marked NOT SET have not been answered yet. -->',
  '',
  ...SECTION_HEADINGS.flatMap((h) => [h, '', '_NOT SET — ask the candidate before relying on this._', '']),
].join('\n');

const FILLED_MD = [
  '# User Profile Context -- career-ops',
  '',
  '## Your Target Roles',
  '',
  '| Archetype | Thematic axes | What they buy |',
  '|-----------|---------------|---------------|',
  '| **AI Platform / LLMOps** | Evaluation, observability | Production AI with metrics |',
  '',
  '## Your Exit Narrative',
  '',
  'Built and sold a SaaS. Now applied AI at scale.',
  '',
  '## Your Location Policy',
  '',
  '_NOT SET — ask the candidate before relying on this._',
  '',
].join('\n');

test('profileMdHasContent ignores headings, the generated-by comment and NOT SET lines', () => {
  assert.equal(profileMdHasContent(EMPTY_MD), false, 'a file of placeholders says nothing');
  assert.equal(profileMdHasContent(FILLED_MD), true);
  for (const nothing of [undefined, null, '', '   ', '# Only a heading']) {
    assert.equal(profileMdHasContent(nothing), false);
  }
});

test('profileMdBlock labels the file and says what it is for', () => {
  const block = profileMdBlock(FILLED_MD);
  assert.match(block, /# CANDIDATE TARGETING \(modes\/_profile\.md\)/);
  assert.match(block, /what they are going for/);
  assert.match(block, /AI Platform \/ LLMOps/);
  // The NOT SET line survives on purpose: it stops a model inventing targeting
  // for a section nobody answered.
  assert.match(block, /NOT SET/);
});

test('profileMdBlock sends nothing at all when there is nothing to say', () => {
  assert.equal(profileMdBlock(EMPTY_MD), '');
  assert.equal(profileMdBlock(undefined), '');
  assert.equal(profileMdBlock(''), '');
});

test('profileMdBlock caps the file text, and the label is the only thing on top', () => {
  const huge = '## Your Target Roles\n\n' + 'x'.repeat(10_000);
  const block = profileMdBlock(huge);
  assert.match(block, /truncated/);
  // The cap bounds the file, not the labelled block — the label is ~100 chars.
  // Callers budget against the returned length, which is why that is the number
  // the builders subtract.
  const labelOverhead = block.length - PROFILE_MD_CAP;
  assert.ok(labelOverhead > 0 && labelOverhead < 200, `label overhead was ${labelOverhead}`);
  assert.ok(profileMdBlock(huge, 300).length < block.length);
  // An uncapped file is passed through whole.
  assert.doesNotMatch(profileMdBlock('## Your Exit Narrative\n\nshort'), /truncated/);
});

const system = 'SYSTEM';
const cv = 'CV CONTENT '.repeat(500);
const profileYaml = 'candidate:\n  full_name: "Jane"\n';
const jd = 'JD CONTENT '.repeat(500);

test('the evaluator is given the targeting file', () => {
  const [, user] = buildEvaluatorMessages({ system, cv, profileYaml, profileMd: FILLED_MD, jd, url: null, numCtx: 16384 });
  assert.match(user.content, /# CANDIDATE TARGETING/);
  assert.match(user.content, /AI Platform \/ LLMOps/);
  // Order matters for small models: profile, targeting, CV, then the JD.
  const i = (s) => user.content.indexOf(s);
  assert.ok(i('# CANDIDATE PROFILE') < i('# CANDIDATE TARGETING'));
  assert.ok(i('# CANDIDATE TARGETING') < i('# CANDIDATE CV'));
  assert.ok(i('# CANDIDATE CV') < i('# JOB DESCRIPTION TO EVALUATE'));
});

test('an absent or empty targeting file leaves the evaluator turn exactly as it was', () => {
  const none = buildEvaluatorMessages({ system, cv, profileYaml, jd, url: null, numCtx: 16384 })[1].content;
  const empty = buildEvaluatorMessages({ system, cv, profileYaml, profileMd: EMPTY_MD, jd, url: null, numCtx: 16384 })[1].content;
  assert.equal(none, empty, 'placeholders must not change the prompt');
  assert.doesNotMatch(none, /# CANDIDATE TARGETING/);
});

test('adding the targeting block cannot push a saturated turn past numCtx', () => {
  // With a short CV there is slack in the budget, so the turn legitimately
  // grows — a cap is a ceiling, not a target. The invariant that matters is the
  // SATURATED case: when the CV and JD are big enough to fill the budget on
  // their own, the targeting block must take its room from them rather than
  // being added on top.
  const numCtx = 16384;
  const bigCv = 'CV '.repeat(60_000);
  const bigJd = 'JD '.repeat(60_000);
  const budget = Math.max(6000, Math.floor(numCtx * 3.5) - system.length - 3500);

  const without = buildEvaluatorMessages({ system, cv: bigCv, profileYaml, jd: bigJd, url: null, numCtx })[1].content;
  const with_ = buildEvaluatorMessages({ system, cv: bigCv, profileYaml, profileMd: FILLED_MD, jd: bigJd, url: null, numCtx })[1].content;

  assert.ok(without.length <= budget * 1.05, `baseline turn ${without.length} already over budget ${budget}`);
  assert.ok(with_.length <= without.length + 10, `saturated turn grew by ${with_.length - without.length} chars`);
  // It gave up CV room, and kept every other section intact.
  assert.match(with_, /# CANDIDATE TARGETING/);
  assert.match(with_, /# JOB DESCRIPTION TO EVALUATE/);
  assert.match(with_, /# CANDIDATE CV/);
  assert.match(with_, /# CANDIDATE PROFILE/);
});

test('a tiny numCtx still yields a usable turn with every section present', () => {
  const [, user] = buildEvaluatorMessages({ system, cv, profileYaml, profileMd: FILLED_MD, jd, url: null, numCtx: 2048 });
  for (const h of ['# CANDIDATE PROFILE', '# CANDIDATE TARGETING', '# CANDIDATE CV', '# JOB DESCRIPTION TO EVALUATE']) {
    assert.match(user.content, new RegExp(h));
  }
});

test('the tailor, the writer and every portal task get it too', () => {
  const tailor = buildTailorMessages({ system, cv, profileYaml, profileMd: FILLED_MD, jd, reportExcerpt: '', numCtx: 16384 })[1].content;
  const writer = buildWriterMessages({ system, cv, profileYaml, profileMd: FILLED_MD, jd, reportExcerpt: '', angle: '', numCtx: 16384 })[1].content;
  const task = buildTaskMessages({ system, cv, profileYaml, profileMd: FILLED_MD, jd, report: '', instruction: 'Do it.', numCtx: 16384 })[1].content;
  for (const c of [tailor, writer, task]) {
    assert.match(c, /# CANDIDATE TARGETING/);
    assert.match(c, /Built and sold a SaaS/);
  }
  // The instruction still lands last in a task turn.
  assert.ok(task.trimEnd().endsWith('Do it.'));
});

test('the task builder omits the block for a candidate who has filled nothing in', () => {
  const none = buildTaskMessages({ system, cv, profileYaml, jd, report: '', instruction: 'Do it.', numCtx: 16384 })[1].content;
  const empty = buildTaskMessages({ system, cv, profileYaml, profileMd: EMPTY_MD, jd, report: '', instruction: 'Do it.', numCtx: 16384 })[1].content;
  assert.equal(none, empty);
});

test('a task turn with no CV at all still works (patterns passes cv: "")', () => {
  const [, user] = buildTaskMessages({ system, cv: '', profileYaml, profileMd: FILLED_MD, instruction: 'Analyse.', numCtx: 16384 });
  assert.match(user.content, /# CANDIDATE TARGETING/);
  assert.doesNotMatch(user.content, /# CANDIDATE CV/);
});

// ---- the prompts have to TELL the model what the block is ----
//
// Shipping the block without saying what it is would have been half a change:
// several prompts enumerate their inputs and say "grounded ONLY in the CV and
// profile", which actively excludes an unexplained section. And a prompt edit
// only reaches members whose stored copy auto-upgrades, which happens solely
// when promptVersion moves (lib/firestore.js).

import {
  APPLY_SYSTEM_PROMPT, CONTACTO_SYSTEM_PROMPT, DEFAULT_AGENTS_CONFIG,
  EVALUATOR_SYSTEM_PROMPT, FOLLOWUP_SYSTEM_PROMPT, INTERVIEW_PREP_SYSTEM_PROMPT,
  PATTERNS_SYSTEM_PROMPT, PROJECT_SYSTEM_PROMPT, RESEARCHER_SYSTEM_PROMPT,
  TAILOR_SYSTEM_PROMPT, TRAINING_SYSTEM_PROMPT, WRITER_SYSTEM_PROMPT,
} from '../lib/prompts.js';

const RECEIVES_TARGETING = {
  EVALUATOR: EVALUATOR_SYSTEM_PROMPT,
  TAILOR: TAILOR_SYSTEM_PROMPT,
  WRITER: WRITER_SYSTEM_PROMPT,
  RESEARCHER: RESEARCHER_SYSTEM_PROMPT,
  CONTACTO: CONTACTO_SYSTEM_PROMPT,
  TRAINING: TRAINING_SYSTEM_PROMPT,
  PROJECT: PROJECT_SYSTEM_PROMPT,
  INTERVIEW_PREP: INTERVIEW_PREP_SYSTEM_PROMPT,
};

test('every prompt that receives the block is told what it is', () => {
  for (const [name, prompt] of Object.entries(RECEIVES_TARGETING)) {
    assert.match(prompt, /CANDIDATE TARGETING/, `${name} never mentions the block`);
    assert.match(prompt, /modes\/_profile\.md/, `${name} does not say which file it is`);
    assert.match(prompt, /NOT SET/, `${name} does not say an unanswered section is unknown`);
  }
});

test('no prompt still says "ONLY ... CV and profile", which would exclude the block', () => {
  const all = { ...RECEIVES_TARGETING, APPLY: APPLY_SYSTEM_PROMPT, FOLLOWUP: FOLLOWUP_SYSTEM_PROMPT };
  for (const [name, prompt] of Object.entries(all)) {
    assert.doesNotMatch(prompt, /ONLY (in )?the candidate's CV and profile/, `${name} still excludes targeting`);
    assert.doesNotMatch(prompt, /ONLY the CV, profile, the card/, `${name} still excludes targeting`);
  }
});

test('the patterns analyst is told the block is the targeting under test, but still needs numbers', () => {
  assert.match(PATTERNS_SYSTEM_PROMPT, /CANDIDATE TARGETING/);
  assert.match(PATTERNS_SYSTEM_PROMPT, /rest on a number from the statistics/);
});

test('promptVersion moved for every agent whose prompt changed', () => {
  // Stored prompts upgrade only when the default version is HIGHER than the
  // stored one. Editing a prompt without bumping this leaves every existing
  // member on the old instructions for ever.
  const { agents } = DEFAULT_AGENTS_CONFIG;
  assert.equal(agents.evaluator.promptVersion, 4);
  assert.equal(agents.tailor.promptVersion, 2);
  assert.equal(agents.writer.promptVersion, 3);
  assert.equal(agents.researcher.promptVersion, 2);
  // Script agents have no prompt and must stay at 0.
  assert.equal(agents.scout.promptVersion, 0);
  assert.equal(agents.extractor.promptVersion, 0);
});

test('every versioned default prompt is non-empty and carries its own version', () => {
  for (const k of ['evaluator', 'tailor', 'writer', 'researcher']) {
    const a = DEFAULT_AGENTS_CONFIG.agents[k];
    assert.ok(a.systemPrompt.length > 200, `${k} prompt looks empty`);
    assert.ok(a.promptVersion >= 1, `${k} is versioned`);
  }
});

test('contacto keeps its own prompt when the researcher default version moves', async () => {
  // Regression: the old test was `cfg.promptVersion > 1`, compared against the
  // shipped researcher default of 1. Bumping that default to 2 made the
  // condition true for everyone and silently switched outreach onto the
  // deep-dive prompt. promptEditedBy is the real signal.
  const src = await readFile(new URL('../jobs/contacto.js', import.meta.url), 'utf8');
  // Comments explain the old heuristic by name, so check the CODE only.
  const code = src.replace(/^\s*\/\/.*$/gm, '');
  assert.match(code, /cfg\.promptEditedBy && cfg\.systemPrompt \? cfg\.systemPrompt : CONTACTO_SYSTEM_PROMPT/);
  assert.doesNotMatch(code, /cfg\.promptVersion > 1/, 'version-number heuristic is back');

  // And the condition itself behaves: untouched → contacto's own prompt;
  // edited by an admin → theirs.
  const pick = (cfg) => (cfg.promptEditedBy && cfg.systemPrompt ? cfg.systemPrompt : CONTACTO_SYSTEM_PROMPT);
  const researcherDefault = DEFAULT_AGENTS_CONFIG.agents.researcher;
  assert.equal(pick(researcherDefault), CONTACTO_SYSTEM_PROMPT, 'a default install must not use the deep-dive prompt');
  assert.equal(pick({ ...researcherDefault, promptVersion: 9 }), CONTACTO_SYSTEM_PROMPT, 'a version bump alone must not switch it');
  assert.equal(pick({ systemPrompt: 'ADMIN EDIT', promptEditedBy: 'admin@example.com' }), 'ADMIN EDIT');
});
